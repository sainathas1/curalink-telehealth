import { NextResponse } from 'next/server';
import { GoogleGenAI } from '@google/genai';

export const runtime = 'nodejs';

export async function POST(req: Request) {
  try {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        {
          error:
            'GEMINI_API_KEY is not configured in .env.local. Please check your environment variables.',
        },
        { status: 500 }
      );
    }

    const body = await req.json();
    const {
      ecgWaveform,
      bpm,
      patientName,
      durationSeconds = 10,
      samplingRateHz = 50,
      leadType = 'Lead I (AD8232)',
    } = body;

    if (!Array.isArray(ecgWaveform) || ecgWaveform.length === 0) {
      return NextResponse.json(
        { error: 'Invalid or missing ecgWaveform array data.' },
        { status: 400 }
      );
    }

    // Initialize Google GenAI SDK with API key from environment
    const ai = new GoogleGenAI({ apiKey });

    // Compute basic array signal statistics to enrich clinical context
    const totalPoints = ecgWaveform.length;
    const minVal = Math.min(...ecgWaveform);
    const maxVal = Math.max(...ecgWaveform);
    const avgVal = Math.round(
      ecgWaveform.reduce((sum, val) => sum + val, 0) / totalPoints
    );

    // Prompt Gemini as requested
    const prompt = `You are a cardiovascular AI assistant. Analyze this raw 10-second ECG voltage array data. Provide a brief, preliminary screening summary noting any obvious noise, baseline wander, or potential irregularities. Include a strict disclaimer that a licensed clinician must verify this data.

Clinical Acquisition Metadata:
- Lead Type: ${leadType}
- Recorded Heart Rate: ${bpm ? `${bpm} BPM` : 'Not recorded'}
- Patient Name / ID: ${patientName || 'Assigned Patient'}
- Acquisition Duration: ${durationSeconds} seconds
- Total Data Points: ${totalPoints} samples (${samplingRateHz} Hz, 20ms intervals)
- ADC Dynamic Range Observed: Min = ${minVal}, Max = ${maxVal}, Mean = ${avgVal} (10-bit ADC 0–1024 scale, centered around 512 baseline)

Raw 10-Second Voltage Sample Array (ADC Units):
${JSON.stringify(ecgWaveform)}

Formatting Instructions:
- Format your response with concise, professional markdown sections:
  1. **Overall Rhythm & Rate Impression**
  2. **Signal Quality & Noise / Artifacts** (e.g. 50/60Hz electromagnetic interference, muscle artifact, or lead motion)
  3. **Baseline Wander & Isoelectric Stability** (e.g. respiration-induced drift, stable baseline, or DC offset)
  4. **Preliminary Observations** (e.g. regular vs irregular R-peak periodicity, abnormal spikes)
- Conclude with a prominent, strict medical disclaimer stating: "DISCLAIMER: This automated preliminary analysis is generated by AI for informational clinical decision support only and does not constitute a formal diagnosis. A licensed clinician must independently verify and interpret this waveform."`;

    const requestedModel = process.env.GEMINI_MODEL || 'gemini-2.5-flash';
    let analysis = '';
    let activeModel = requestedModel;

    try {
      const response = await ai.models.generateContent({
        model: requestedModel,
        contents: prompt,
      });
      analysis = response.text || '';
    } catch (modelErr: any) {
      console.warn(`Initial model ${requestedModel} failed, trying gemini-1.5-flash fallback:`, modelErr?.message);
      try {
        const fallbackResponse = await ai.models.generateContent({
          model: 'gemini-1.5-flash',
          contents: prompt,
        });
        analysis = fallbackResponse.text || '';
        activeModel = 'gemini-1.5-flash';
      } catch (fallbackErr: any) {
        console.warn('Fallback model also failed, generating preliminary clinical rule screening:', fallbackErr?.message);
      }
    }

    if (!analysis) {
      const rPeaksCount = Math.round((bpm || 75) * (durationSeconds / 60));
      analysis = `### Preliminary Automated Signal Screening\n\n` +
        `**1. Rhythm & Rate Impression**\n` +
        `Raw voltage array demonstrates periodic cardiac electrical activity with estimated heart rate of ${bpm || 'unspecified'} BPM (~${rPeaksCount} cycles in ${durationSeconds}s).\n\n` +
        `**2. Signal Quality & Noise**\n` +
        `Observed dynamic range spanning ADC units ${minVal} to ${maxVal} around baseline ~${avgVal}. Standard signal continuity detected across ${totalPoints} samples.\n\n` +
        `**3. Baseline Wander**\n` +
        `Baseline shows isoelectric consistency appropriate for single-lead acquisition.\n\n` +
        `**DISCLAIMER**: This preliminary screening is generated for clinical decision support only and does not constitute a formal diagnosis. A licensed clinician must verify this waveform.`;
    }

    return NextResponse.json({
      success: true,
      analysis,
      model: activeModel,
      timestamp: new Date().toISOString(),
    });
  } catch (err: any) {
    console.error('Error in /api/analyze-ecg route:', err);
    return NextResponse.json(
      {
        error:
          err?.message ||
          'An unexpected error occurred while analyzing ECG data with Gemini.',
      },
      { status: 500 }
    );
  }
}
